rows = []
with RAW.open(encoding="utf-8") as f:
    for r in csv.DictReader(f):
        token = r["cited_path"]
        if token in DROP or token.endswith("top5.png"):
            continue
        path = r["resolved_path"]
        note = ""
        exists = r["exists"]
        if path.endswith("comparison/renders/route_labeled.png"):
            exists = "n/a (fix-log quote)"
            note = "comparison/STATUS.md line 45 quotes the old path while describing the fix; the live links point to ../clouds2/renders/route_labeled.png."
        if path.endswith("comparison/frames/srred_iso.png") or path.endswith("comparison/frames/srorg_iso.png"):
            exists = "NO (missing prefix)"
            note = "The file exists at ../minigames/other/frames/" + path.rsplit("/", 1)[-1] + "; comparison/data/contradiction_resolution.md line 76 omits the prefix."
        if path.endswith("city_marathon/renders/station_iso.png"):
            note = "No such file; only station_interior_iso.png and frames/10_station_iso.png exist."
        if path.startswith("game-plugins/research/existing_maps/yeti_set_go/textures/"):
            exists = "yes (documented base)"
            note = "README line 254 defines the base as pack/extracted/assets/minecraft/; the file exists there."
        opened = "yes" if path in OPENED else "no (PIL dimensions only)"
        if path in OPENED:
            matches = "yes" if not note else "partial"
        else:
            matches = "not opened"
        rows.append({
            "agent": r["agent"],
            "cited_path": token,
            "resolved_path": path,
            "exists": exists,
            "width": r["width"],
            "height": r["height"],
            "opened_by_a14": opened,
            "matches_caption": matches,
            "notes": note,
        })

with OUT.open("w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=["agent", "cited_path", "resolved_path", "exists", "width", "height", "opened_by_a14", "matches_caption", "notes"])
    w.writeheader()
    w.writerows(rows)
print(f"wrote {len(rows)} rows")
print(f"opened: {sum(1 for r in rows if r['opened_by_a14']=='yes')}")
print(f"missing: {sum(1 for r in rows if not r['exists'].startswith('yes'))}")
