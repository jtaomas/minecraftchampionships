def risk(r):
    c=r["command"]
    if "summon firework_rocket" in c: return "HIGH: legacy firework entity/item NBT"
    if c.startswith("/item replace") and "{" in c and any(k in c for k in ["CanPlaceOn","CanDestroy","Unbreakable","Enchantments","Potion:"]): return "HIGH: legacy item NBT -> 1.21 components"
    if "CanPlaceOn" in c or "CanDestroy" in c: return "HIGH: legacy item NBT -> 1.21 components"
    return "OK"
with open("data/commands.csv","w",newline="",encoding="utf-8") as f:
    w=csv.writer(f); w.writerow(["id","cluster","x","y","z","kind","auto","condition_met","category","command","effect","risk_1_21","confidence"])
    for i,r in enumerate(rows,1):
        w.writerow([i,r["cluster"],r["x"],r["y"],r["z"],r["kind"],r["auto"],r["condition_met"],classify(r),r["command"],effect(r),risk(r),"H"])
