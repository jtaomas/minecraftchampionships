    if 959<=x<=975 and y==10 and z==-6: return "timer_control"
    if x==978 and 10<=y<=23 and z==-8: return "container_reset"
    if x==975 and y==10 and z==-14: return "item_cleanup"
    if x==978 and y==23 and z==-8: return "item_cleanup"
