    if cat=="container_reset": return "removes a loot container (destroy)"
    if cat=="item_cleanup": return "kills dropped items"
    if cat=="start_trigger": return "moves level-8 team players to level 9 (countdown)"
    if cat=="fail_safe": return "teleports stranded players back to centre"
    if cat=="death_handling": return "death score -> spectator + level 14, then reset score"
    if cat=="post_game": return "clears winners / moves them to pve lobby team"
    if cat=="reset_control": return "clears the reset/win redstone pulse"
    if cat=="control_reset": return "clears control redstone"
    if cat=="game_end_sound": return "stops music and rings bell at game end"
    if cat=="start_reset": return "starts/clears players for the next round"
    if cat=="timer": return "increments timer_skybattle once per second"
    if cat=="team_join_kit": return "team join / team wool / mining reward"
    if cat=="lobby_button": return "arena-lobby button pulse"
    if c.startswith("/fill") and "redstone_block" in c: return "pulses a redstone line"
    if c.startswith("/fill") and "destroy" in c: return "removes a loot container"
