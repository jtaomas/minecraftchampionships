import numpy as np, sys, os, gzip, struct, collections, json, re, hashlib

OUT = r"C:\Users\LeonS\AppData\Local\Temp\opencode\bb_imports\out"
PREV = r"C:\Users\LeonS\AppData\Local\Temp\opencode\work\prev"
os.makedirs(OUT, exist_ok=True)
os.makedirs(PREV, exist_ok=True)

COMMAND = {"command_block", "chain_command_block", "repeating_command_block", "structure_block", "structure_void", "jigsaw"}
REDSTONE = {"redstone_wire", "repeater", "comparator", "observer", "piston", "sticky_piston", "piston_head", "moving_piston",
            "redstone_torch", "redstone_wall_torch", "lever", "tripwire", "tripwire_hook", "daylight_detector", "hopper",
            "dropper", "dispenser", "note_block", "redstone_block", "tnt", "target", "jukebox", "bell", "lectern"}
CONTAINER = {"item_frame_block", "chest", "trapped_chest", "barrel", "ender_chest", "furnace", "blast_furnace", "smoker", "brewing_stand"}
RENAME = {"grass": "short_grass", "tall_grass_x": "tall_grass"}
STATE_RE = re.compile(r"^minecraft:[a-z0-9_]{1,64}(\[[a-z0-9_]{1,32}=[a-z0-9_]{1,32}(,[a-z0-9_]{1,32}=[a-z0-9_]{1,32}){0,15}])?$")


def category(base):
    if base in COMMAND:
        return "command"
    if base in REDSTONE or base.endswith(("_button", "_pressure_plate")):
        return "redstone"
    if base.endswith(("_sign", "_wall_sign", "_hanging_sign", "_wall_hanging_sign")):
        return "sign"
    if base.endswith(("_banner", "_wall_banner", "_head", "_wall_head", "_skull", "_wall_skull")):
        return "banner_head"
    if base in CONTAINER:
        return "container"
    if base in ("allow", "deny", "border_block"):
        return "bedrock_logic"
    return None


def load(npz):
    d = np.load(npz, allow_pickle=True)
    return d["X"], d["Y"], d["Z"], d["P"], list(d["pal"])


def clean_state(s):
    base = s.split("[")[0].replace("minecraft:", "")
    base2 = RENAME.get(base, base)
    if base2 != base:
        s = "minecraft:" + base2 + (s[s.index("["):] if "[" in s else "")
    if not STATE_RE.match(s):
        s = "minecraft:" + base2
    return s


def build(spec, X, Y, Z, P, pal):
    """spec: id,name,credit,origin (ox,oy,oz), centre_local (cx,cy,cz), size_c (w,d), spawn_a, spawn_b, gates_a, gates_b.
    X,Y,Z are LOCAL coordinates already; P indexes pal."""
    stats = collections.Counter()
    cat = {}
    keep = np.zeros(len(P), dtype=bool)
    newpal = []
    pmap = {}
    idx = np.full(len(pal), -1, dtype=np.int64)
    for i, s in enumerate(pal):
        base = s.split("[")[0].replace("minecraft:", "")
        c = category(base)
        cat[i] = c
        if c is None and base not in ("air", "cave_air", "void_air"):
            cs = clean_state(s)
            if cs not in pmap:
                pmap[cs] = len(newpal)
                newpal.append(cs)
            idx[i] = pmap[cs]
    cnt = collections.Counter()
    sel = idx[P] >= 0
    for i in np.unique(P[~sel]):
        n = int((P == i).sum())
        if cat.get(i):
            cnt[cat[i]] += n
    # gate boxes are generated by the plugin in team colours: remove whatever the map has there
    gate_removed = 0
    gmask = np.zeros(len(P), dtype=bool)
    for box in spec["gates_a"] + spec["gates_b"]:
        gmask |= (X >= box[0]) & (X <= box[3]) & (Y >= box[1]) & (Y <= box[4]) & (Z >= box[2]) & (Z <= box[5])
    gate_removed = int((gmask & sel).sum())
    sel &= ~gmask
    for box in spec.get("remove_boxes", []):
        sel &= ~((X >= box[0]) & (X <= box[3]) & (Y >= box[1]) & (Y <= box[4]) & (Z >= box[2]) & (Z <= box[5]))
    xs, ys, zs, ps = X[sel], Y[sel], Z[sel], idx[P[sel]]
    # centre pad: the plugin writes the neutral blocks itself; drop the map's own pad cells
    cx, cy, cz = spec["centre"]
    w, dd = spec["centre_size"]
    x0, z0 = cx - w // 2, cz - dd // 2
    padmask = (ys == cy) & (xs >= x0) & (xs < x0 + w) & (zs >= z0) & (zs < z0 + dd)
    pad_removed = int(padmask.sum())
    xs, ys, zs, ps = xs[~padmask], ys[~padmask], zs[~padmask], ps[~padmask]
    adds = spec.get("add", [])
    if adds:
        addpal = {}
        ax, ay, az, ap = [], [], [], []
        for (x, y, z, s) in adds:
            if s not in pmap:
                pmap[s] = len(newpal)
                newpal.append(s)
            ax.append(x); ay.append(y); az.append(z); ap.append(pmap[s])
        # added blocks replace whatever the map had at that position
        keep_old = np.ones(len(xs), dtype=bool)
        for x, y, z in zip(ax, ay, az):
            keep_old &= ~((xs == x) & (ys == y) & (zs == z))
        xs = np.concatenate([xs[keep_old], np.array(ax)]); ys = np.concatenate([ys[keep_old], np.array(ay)])
        zs = np.concatenate([zs[keep_old], np.array(az)]); ps = np.concatenate([ps[keep_old], np.array(ap)])
    used = np.unique(ps)
    remap = np.full(len(newpal), -1, dtype=np.int64)
    remap[used] = np.arange(len(used))
    newpal = [newpal[i] for i in used]
    ps = remap[ps]
    assert xs.min() >= -48 and xs.max() <= 48 and zs.min() >= -48 and zs.max() <= 48, (xs.min(), xs.max(), zs.min(), zs.max())
    os.makedirs(os.path.join(OUT, spec["id"]), exist_ok=True)
    bpath = os.path.join(OUT, spec["id"], "blocks.mcmi.gz")
    with gzip.GzipFile(bpath, "wb", mtime=0) as f:
        f.write(b"MCMI")
        f.write(struct.pack(">ii", 1, len(newpal)))
        for s in newpal:
            e = s.encode("utf-8")
            f.write(struct.pack(">H", len(e)) + e)
        f.write(struct.pack(">i", len(xs)))
        rec = np.zeros(len(xs), dtype=[("x", ">i2"), ("y", ">i2"), ("z", ">i2"), ("p", ">i4")])
        rec["x"], rec["y"], rec["z"], rec["p"] = xs, ys, zs, ps
        f.write(rec.tobytes())
    sizes = (int(xs.max() - xs.min() + 1), int(ys.max() - ys.min() + 1), int(zs.max() - zs.min() + 1))
    yml = []
    yml.append(f"id: {spec['id']}")
    yml.append(f"name: \"{spec['name']}\"")
    yml.append(f"credit: \"{spec['credit']}\"")
    yml.append(f"license: \"{spec['license']}\"")
    yml.append(f"size: [{sizes[0]}, {sizes[1]}, {sizes[2]}]")
    yml.append("floor_y: 0")
    yml.append(f"centre: [{cx}, {cy}, {cz}]")
    yml.append(f"centre_size: [{w}, {dd}]")
    yml.append(f"spawn_a: [{spec['spawn_a'][0]}, {spec['spawn_a'][1]}, {spec['spawn_a'][2]}]")
    yml.append(f"spawn_b: [{spec['spawn_b'][0]}, {spec['spawn_b'][1]}, {spec['spawn_b'][2]}]")
    yml.append("gates_a: [" + ", ".join("[" + ", ".join(map(str, b)) + "]" for b in spec["gates_a"]) + "]")
    yml.append("gates_b: [" + ", ".join("[" + ", ".join(map(str, b)) + "]" for b in spec["gates_b"]) + "]")
    yml.append("blocks: blocks.mcmi.gz")
    open(os.path.join(OUT, spec["id"], "map.yml"), "w", encoding="utf-8", newline="\n").write("\n".join(yml) + "\n")
    # preview dump (local coords shifted to >= 0)
    mn = (int(xs.min()), int(ys.min()), int(zs.min()))
    with gzip.open(os.path.join(PREV, spec["id"] + ".mcmdump.gz"), "wt") as f:
        f.write(f"MCMDUMP 1 {sizes[0]} {sizes[1]} {sizes[2]}\n")
        for x, y, z, p in zip(xs, ys, zs, ps):
            f.write(f"{x - mn[0]} {y - mn[1]} {z - mn[2]} {newpal[p]}\n")
    rep = dict(id=spec["id"], blocks=int(len(xs)), palette=len(newpal), stripped=dict(cnt), gate_blocks_replaced=gate_removed,
               pad_cells_replaced=pad_removed, size=sizes, bounds_min=mn, bounds_max=(int(xs.max()), int(ys.max()), int(zs.max())))
    json.dump(rep, open(os.path.join(PREV, spec["id"] + ".report.json"), "w"))
    print(json.dumps(rep))
    return rep


